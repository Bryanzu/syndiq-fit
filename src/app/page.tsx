/* DASHBOARD — returning users                                        */
/* ------------------------------------------------------------------ */
function Dashboard({ program, mealPlan }: { program: WorkoutProgram; mealPlan: any | null }) {
  const [log, setLog] = useState<SessionEntry[]>([]);
  useEffect(() => {
    const refresh = () => setLog(loadWorkoutLog());
    refresh();
    // The workout player logs sessions while this page stays mounted
    window.addEventListener(WORKOUT_LOGGED_EVENT, refresh);
    return () => window.removeEventListener(WORKOUT_LOGGED_EVENT, refresh);
  }, []);
  const workout = useWorkoutSession();

  const todayISO = toLocalISODate();
  const todayEntry = log.find((e) => e.date === todayISO);
  const weekDates = useMemo(() => getWeekDates(), []);
  const weekISO = weekDates.map((d) => toLocalISODate(d));
  const doneThisWeek = new Set(log.filter((e) => weekISO.includes(e.date)).map((e) => e.date));
  const sessionsThisWeek = log.filter((e) => weekISO.includes(e.date)).length;
  const target = program.userProfile.frequency && typeof program.userProfile.frequency === 'number' ? program.userProfile.frequency : program.days.length;

  const nextIdx = getNextDayIndex(program, log);
  const day = program.days[nextIdx] ?? program.days[0];
  const exercises = day?.exercises ?? [];

  const todayMeals: any[] = useMemo(() => {
    if (!mealPlan?.days?.length) return [];
    const idx = (new Date().getDay() + 6) % 7;
    return (mealPlan.days[idx] ?? mealPlan.days[0])?.meals ?? [];
  }, [mealPlan]);
  const todayKcal = todayMeals.reduce((s, m) => s + (m.calories || 0), 0);

  const recent = [...log].sort((a, b) => b.completedAt.localeCompare(a.completedAt)).slice(0, 4);
  const isBodyweight = program.userProfile.availableEquipment.length === 0 || program.userProfile.availableEquipment.includes('bodyweight_only' as any);

  const complete = () => setLog(logSession({ date: todayISO, dayNumber: day.dayNumber, title: day.title }));
  const undo = () => todayEntry && setLog(undoSession(todayEntry.date, todayEntry.dayNumber));

  const heroLabel = todayEntry ? 'Up next' : "Today's workout";
  const title = day.title.replace(/^Day \d+\s*[—–-]\s*/, '');

  return (
    <div className="page py-6 lg:py-10 animate-fadeIn">
      <header className="flex items-end justify-between gap-4 mb-6 lg:mb-8">
        <div>
          <p className="t-eyebrow">{new Date().toLocaleDateString(undefined, { weekday: 'long', day: 'numeric', month: 'long' })}</p>
          <h1 className="t-title mt-1">{greeting()}</h1>
        </div>
        <Link href="/questionnaire" className="btn-ghost btn-sm hidden sm:inline-flex">
          <RotateCcw className="w-4 h-4" /> Recalibrate
        </Link>
      </header>

      {/* Week strip */}
      <section aria-label="This week" className="mb-6 lg:mb-8">
        <div className="flex items-center justify-between mb-3">
          <h2 className="t-section">This week</h2>
          <span className="t-small">
            <strong className="text-gym-text font-semibold">{sessionsThisWeek}</strong> of {target} sessions
          </span>
        </div>
        <ol className="grid grid-cols-7 gap-1.5 sm:gap-3">
          {weekDates.map((d, i) => {
            const iso = weekISO[i];
            const isToday = iso === todayISO;
            const done = doneThisWeek.has(iso);
            return (
              <li key={iso} className="flex flex-col items-center gap-1.5">
                <span className={`text-xs ${isToday ? 'text-gym-text font-semibold' : 'text-gym-textMuted'}`}>{WEEKDAY_SHORT[i]}</span>
                <span
                  className={`flex size-9 sm:size-11 items-center justify-center rounded-full text-sm font-medium transition-colors ${
                    done
                      ? 'bg-gym-lime text-gym-ink'
                      : isToday
                      ? 'bg-gym-cardInner text-gym-text ring-2 ring-gym-lime/70'
                      : 'bg-gym-card text-gym-textMuted'
                  }`}
                  aria-label={`${WEEKDAY_SHORT[i]} ${d.getDate()}${done ? ', workout completed' : ''}`}
                >
                  {done ? <Check className="w-4 h-4" strokeWidth={3} /> : d.getDate()}
                </span>
              </li>
            );
          })}
        </ol>
      </section>

      <div className="grid grid-cols-1 gap-8 lg:grid-cols-12 lg:gap-10">
        {/* Workout column */}
        <div className="lg:col-span-7 min-w-0 space-y-8">
          <section aria-label={heroLabel}>
            <div className="relative isolate overflow-hidden rounded-3xl">
              <Image src="/images/workout-empty.jpg" alt="" fill sizes="(max-width: 1024px) 100vw, 58vw" className="object-cover -z-20" />
              <div className="absolute inset-0 -z-10 bg-gradient-to-t from-black/90 via-black/60 to-black/30" />
              <div className="p-6 sm:p-8 pt-24 sm:pt-32 space-y-4 text-white">
                <p className="text-xs font-semibold uppercase tracking-[0.16em] text-gym-lime">{heroLabel}</p>
                <div>
                  <h2 className="text-2xl sm:text-3xl font-semibold tracking-tight">{title}</h2>
                  <p className="text-sm text-white/70 mt-1">
                    {day.focusMuscles.slice(0, 4).map(formatMuscle).join(' · ')}
                  </p>
                </div>
                <div className="flex flex-wrap gap-2 text-xs">
                  <span className="inline-flex items-center gap-1.5 rounded-full bg-white/15 px-3 py-1.5 backdrop-blur">
                    <Clock className="w-3.5 h-3.5" /> {day.estimatedDuration} min
                  </span>
                  <span className="inline-flex items-center gap-1.5 rounded-full bg-white/15 px-3 py-1.5 backdrop-blur">
                    <Dumbbell className="w-3.5 h-3.5" /> {exercises.length} exercises
                  </span>
                  <span className="inline-flex items-center gap-1.5 rounded-full bg-white/15 px-3 py-1.5 backdrop-blur">
                    {isBodyweight ? 'Bodyweight' : 'Equipment'}
                  </span>
                </div>
                <div className="flex flex-wrap items-center gap-2.5 pt-1">
                  <button type="button" onClick={() => workout.start(program, nextIdx)} className="btn-primary px-6">
                    {workout.isActiveFor(day) ? 'Resume workout' : 'Start workout'}{' '}
                    <ArrowRight className="w-4 h-4" />
                  </button>
                  {todayEntry ? (
                    <button type="button" onClick={undo} className="btn bg-white/15 text-white backdrop-blur hover:bg-white/25">
                      <Check className="w-4 h-4" /> Done today <Undo2 className="w-3.5 h-3.5 opacity-70" />
                    </button>
                  ) : (
                    <button type="button" onClick={complete} className="btn bg-white/15 text-white backdrop-blur hover:bg-white/25">
                      <Check className="w-4 h-4" /> Mark complete
                    </button>
                  )}
                </div>
              </div>
            </div>
          </section>

          <section aria-label="Exercises in this session">
            <div className="flex items-center justify-between mb-1">
              <h2 className="t-section">In this session</h2>
              <Link href="/program" className="text-sm font-medium text-gym-limeDark dark:text-gym-lime hover:underline">
                See all
              </Link>
            </div>
            <ul className="divide-line">
              {exercises.slice(0, 5).map((it, i) => (
                <li key={it.exercise.id + i} className="row">
                  <span className="w-6 text-sm text-gym-textMuted tabular-nums">{i + 1}</span>
                  <div className="min-w-0 flex-1">
                    <p className="text-sm sm:text-base font-medium text-gym-text truncate">{it.exercise.name}</p>
                    <p className="t-small capitalize truncate">{it.exercise.primaryMuscles.map(formatMuscle).join(', ')}</p>
                  </div>
                  <span className="text-sm font-semibold text-gym-limeDark dark:text-gym-lime tabular-nums shrink-0">
                    {it.sets} × {it.reps}
                  </span>
                </li>
              ))}
            </ul>
          </section>
        </div>

        {/* Side column */}
        <aside className="lg:col-span-5 min-w-0 space-y-8">
          <section aria-label="Today's meals">
            <div className="flex items-center justify-between mb-1">
              <h2 className="t-section">Today&apos;s meals</h2>
              <Link href="/meal-planner" className="text-sm font-medium text-gym-limeDark dark:text-gym-lime hover:underline">
                {mealPlan ? 'Open planner' : 'Create plan'}
              </Link>
            </div>
            {todayMeals.length > 0 ? (
              <>
                <ul className="divide-line">
                  {todayMeals.map((m, i) => (
                    <li key={m.id ?? i} className="row">
                      <div className="min-w-0 flex-1">
                        <p className="t-small capitalize">{m.mealType}</p>
                        <p className="text-sm sm:text-base font-medium text-gym-text truncate">{m.recipeName}</p>
                      </div>
                      <span className="text-sm text-gym-textMuted tabular-nums shrink-0">{Math.round(m.calories)} kcal</span>
                    </li>
                  ))}
                </ul>
                <p className="t-small mt-2">
                  Total <strong className="text-gym-text font-semibold">{Math.round(todayKcal)} kcal</strong>
                </p>
              </>
            ) : (
              <div className="relative isolate overflow-hidden rounded-2xl mt-2">
                <Image src="/images/meal-prep-healthy.jpg" alt="" fill sizes="(max-width: 1024px) 100vw, 40vw" className="object-cover -z-20" />
                <div className="absolute inset-0 -z-10 bg-black/60" />
                <div className="p-5 space-y-3 text-white">
                  <p className="text-sm text-white/85">No meal plan yet. Build a seven-day Nigerian plan matched to your goal.</p>
                  <Link href="/meal-planner" className="btn-primary btn-sm">Build meal plan</Link>
                </div>
              </div>
            )}
          </section>

          <section aria-label="Recent activity">
            <h2 className="t-section mb-1">Recent activity</h2>
            {recent.length > 0 ? (
              <ul className="divide-line">
                {recent.map((e) => (
                  <li key={e.id} className="row">
                    <span className="inline-flex size-8 items-center justify-center rounded-full bg-gym-lime/15 text-gym-limeDark dark:text-gym-lime shrink-0">
                      <Check className="w-4 h-4" strokeWidth={3} />
                    </span>
                    <div className="min-w-0 flex-1">
                      <p className="text-sm font-medium text-gym-text truncate">{e.title.replace(/^Day \d+\s*[—–-]\s*/, '')}</p>
                      <p className="t-small">
                        {new Date(e.date + 'T00:00:00').toLocaleDateString(undefined, { weekday: 'short', day: 'numeric', month: 'short' })}
                        {e.durationMin ? ` · ${e.durationMin} min` : ''}
                        {e.setsCompleted ? ` · ${e.setsCompleted} sets` : ''}
                      </p>
                    </div>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="t-small py-3">Completed sessions will appear here. Tap “Mark complete” after you train.</p>
            )}
          </section>
        </aside>
      </div>
    </div>
  );
}

/* ------------------------------------------------------------------ */
export default function HomePage() {
  const [ready, setReady] = useState(false);
  const [program, setProgram] = useState<WorkoutProgram | null>(null);
  const [mealPlan, setMealPlan] = useState<any | null>(null);

  useEffect(() => {
    setProgram(loadActiveProgram());
    setMealPlan(loadActiveMealPlan());
    setReady(true);
  }, []);

  if (!ready) return <div className="min-h-[70dvh]" aria-hidden />;
  return program ? <Dashboard program={program} mealPlan={mealPlan} /> : <Welcome />;
}
